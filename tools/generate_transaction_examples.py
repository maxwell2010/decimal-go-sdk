def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check', action='store_true');args=parser.parse_args()
    outputs,count,profiles=render()
    stale=[]
    for path, content in outputs.items():
        target=ROOT/path
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8')!=content: stale.append(path)
        else:
            target.parent.mkdir(parents=True, exist_ok=True);target.write_text(content,encoding='utf-8')
    if stale: raise SystemExit('stale transaction examples: '+', '.join(stale))
    print(f'{count} write builder examples across {profiles} profiles; '+('checked' if args.check else 'generated'))

if __name__=='__main__': main()
